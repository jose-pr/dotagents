class Findings(LoggingArgs, Cli):
    """Findings queue for a scope. Scope flags go on the subcommand: `findings list -g`.

    Default scope is the project (`<project>/.agents/findings/`); `-g` uses the
    user store, `--agents-dir` overrides it, `--dir` points at any findings
    directory -- each accepted by every subcommand (`findings add -g ...`,
    `findings done -g <name> -r ...`), not by `findings` itself."""

    _parsername_ = "findings"

    class _Base(DotAgentsArgs):
        """Shared scope + `--dir` fields (nested: not a command of its own)."""

        dir: Optional[Path] = None
        "Findings directory override (default: <scope>/findings)."
        ("--dir",)

        def store(self) -> FindingsStore:
            """The queue root: `--dir`, else `<scope-root>/findings/`.

            `resolve_scope` defaults the `-g` store through `resolve_user_store`
            (`--agents-dir`, then `$AGENTS_HOME`, then `~/.agents`), so a pinned
            store is honoured here exactly as in `env` / `context`."""
            if self.dir:
                root = Path(self.dir).expanduser()
            else:
                root = self.resolve_scope().agents_root / FINDINGS_DIRNAME
            return FindingsStore(root)

    class Add(_Base):
        """Record a new finding (one-line description; optional body with details).

        The description becomes the index line; `--body` / `--body-file` carry
        the details."""

        _parsername_ = "add"

        description: str = ""
        "One-line summary of the finding (becomes the index line)."
        ("description",)

        name: Optional[str] = None
        "File name (slug) to use instead of one derived from the description."
        ("--name", "-n")

        body: Optional[str] = None
        "Details (markdown). Default: the description."
        ("--body", "-b")

        body_file: Optional[Path] = None
        "Read the details from a file (`-` = stdin)."
        ("--body-file",)

        def __call__(self) -> int:
            body = _read_text_arg(self.body, self.body_file) or ""
            finding = self.store().add(self.description, name=self.name, body=body)
            self._logger_.info("added finding %s", finding.name)
            print(finding.path)
            return 0

    class List(_Base):
        """List findings (active by default; --all, --processed, --json).

        `--all` lists both states, `--processed` only the addressed ones,
        `--json` gives a machine-readable list."""

        _parsername_ = "list"

        all: bool = False
        "Include processed findings."
        ("--all", "-a")

        processed: bool = False
        "Only processed findings."
        ("--processed",)

        as_json: bool = False
        "Emit JSON."
        ("--json",)

        def __call__(self) -> int:
            store = self.store()
            if self.processed:
                findings = store.processed()
            elif self.all:
                findings = store.all()
            else:
                findings = store.active()
            if self.as_json:
                _write_stdout(json.dumps({
                    "dir": str(store.root),
                    "findings": [
                        {k: v for k, v in f.as_dict().items() if k != "body"}
                        for f in findings
                    ],
                }, indent=2) + "\n")
                return 0
            if not findings:
                self._logger_.info("no findings under %s", store.root)
                return 0
            show_status = self.all
            for f in findings:
                prefix = "[%s] " % f.status if show_status else ""
                _write_stdout("%s%s: %s\n" % (prefix, f.name, f.description))
            return 0

    class Show(_Base):
        """Print one finding, the whole file (--json for a structured form)."""

        _parsername_ = "show"

        name: str = ""
        "Finding name (the index/file name)."
        ("name",)

        as_json: bool = False
        "Emit JSON."
        ("--json",)

        def __call__(self) -> int:
            finding = self.store().require(self.name)
            if self.as_json:
                _write_stdout(json.dumps(finding.as_dict(), indent=2) + "\n")
            else:
                _write_stdout(finding.render())
            return 0

    class Done(_Base):
        """Mark a finding addressed: append the resolution, move it to processed/.

        The resolution is required -- a processed finding without one is
        untriaged, not done."""

        _parsername_ = "done"

        name: str = ""
        "Finding name."
        ("name",)

        resolution: Optional[str] = None
        "The decision, evidence, or why no action was needed."
        ("--resolution", "-r")

        resolution_file: Optional[Path] = None
        "Read the resolution from a file (`-` = stdin)."
        ("--resolution-file",)

        def __call__(self) -> int:
            resolution = _read_text_arg(self.resolution, self.resolution_file) or ""
            finding = self.store().done(self.name, resolution)
            self._logger_.info("processed finding %s", finding.name)
            print(finding.path)
            return 0

    class Reopen(_Base):
        """Move a processed finding back to the active queue."""

        _parsername_ = "reopen"

        name: str = ""
        "Finding name."
        ("name",)

        def __call__(self) -> int:
            finding = self.store().reopen(self.name)
            self._logger_.info("reopened finding %s", finding.name)
            print(finding.path)
            return 0

    class Remove(_Base):
        """Delete a finding recorded by mistake (prefer `done` for a real one).

        The queue discipline is move-never-delete; this is the exception for a
        finding that should never have been recorded."""

        _parsername_ = "remove"

        name: str = ""
        "Finding name."
        ("name",)

        def __call__(self) -> int:
            path = self.store().remove(self.name)
            self._logger_.info("removed %s", path)
            print(path)
            return 0

    class Index(_Base):
        """Regenerate INDEX.md from the files (after hand edits)."""

        _parsername_ = "index"

        def __call__(self) -> int:
            print(self.store().write_index())
            return 0

    class PathCmd(_Base):
        """Print the findings directory for the scope."""

        _parsername_ = "path"

        def __call__(self) -> int:
            print(self.store().root)
            return 0

    _subcommands_ = [Add, List, Show, Done, Reopen, Remove, Index, PathCmd]

    def __call__(self) -> int:
        self._logger_.info(
            "pick a findings subcommand: add, list, show, done, reopen, remove, index, path"
        )
        return 0
