"""`dotagents plans` -- one way to write, read, update, index and move plans.

A plan is read on every executor pass and updated at every step, so the cost
that matters is how much of it has to be read and rewritten each time. This
command makes each of those a small operation: read one section, flip one box,
append one fact, move one file.

**Where**: ``<project>/.agents/plans/``. Plans belong to a project; there is no
user-store queue. ``--dir`` points at any other plans directory.

**Layout**::

    plans/
        INDEX.md                regenerated by every mutating command
        <name>.md               a live plan: draft, ready, review or executing
        <name>/<sub>.md         a sub-plan of <name>
        on-hold/<name>.md       parked
        completed/<name>.md     done; its sub-plans move with it

**File shape** -- the one in ``references/plan_template.md``; this command reads
and edits exactly these parts::

    # <Title>

    Status: draft | ready | review | executing | on-hold | done
    Executor: <family/subrole> -- <why>

    ## Progress

    - [ ] Phase 1: <name>               pending
    - [/] Phase 2: <name>               active
    - [x] Phase 3: <name> — <outcome>   done
    - [!] Phase 4: <name> — <reason>    blocked

    ## Known Facts & Context
    ## Phases
    ### Phase 1: <name>
    ## Verification
    ## Reporting

**Reading less**: ``next`` prints the head, the progress list and the one phase
to work on; ``show --section`` and ``show --phase`` print one part; ``list`` is
one line per plan.

**Writing less**: ``start``, ``check``, ``block`` and ``uncheck`` change one
progress line; ``note`` appends one fact; ``status`` sets the plan's state and
moves the file when the state says so. Each prints one line.

Every subcommand is a class nested inside :class:`Plans`: command discovery
registers each module-level command class as a top-level command, and nesting
keeps ``add`` and ``list`` from becoming ``dotagents add`` and ``dotagents list``.
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path
from typing import Optional

from duho import Cli, LoggingArgs

from dotagents.cli import DotAgentsArgs


def _load_model():
    """The model beside this overlay's `lib/`, by path: the command works
    whether or not that directory is on `sys.path`."""
    path = Path(__file__).resolve().parents[1] / "lib" / "_plans.py"
    spec = importlib.util.spec_from_file_location("_dotagents_plans", path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


_plans = _load_model()
PlansStore = _plans.PlansStore
PLANS_DIRNAME = _plans.PLANS_DIRNAME
SECTIONS = _plans.SECTIONS
LIVE = _plans.LIVE
_fail = _plans._fail


def _out(text: str) -> None:
    """Write to stdout whatever its encoding can represent."""
    try:
        sys.stdout.write(text)
    except UnicodeEncodeError:
        encoding = sys.stdout.encoding or "ascii"
        sys.stdout.write(text.encode(encoding, "replace").decode(encoding))


